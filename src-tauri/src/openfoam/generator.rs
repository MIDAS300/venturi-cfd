fn gen_allrun(case: &CfdCase, solver_cmd: &str) -> String {
    let mut script = String::from(
        r#"#!/usr/bin/env bash
cd "${0%/*}" || exit 1

if ! command -v blockMesh >/dev/null 2>&1; then
    for rc in /opt/openfoam*/etc/bashrc /usr/lib/openfoam/openfoam*/etc/bashrc; do
        if [ -f "$rc" ]; then
            # shellcheck disable=SC1090
            source "$rc"
            break
        fi
    done
fi

set -eo pipefail

echo "[Venturi] Generating background mesh (blockMesh)..."
blockMesh | tee log.blockMesh
"#,
    );

    if case.mesh.snappy_enabled {
        script.push_str(
            r#"
echo "[Venturi] Running snappyHexMesh..."
snappyHexMesh -overwrite | tee log.snappyHexMesh
"#,
        );
    }

    script.push_str(
        r#"
echo "[Venturi] Checking mesh quality..."
checkMesh | tee log.checkMesh
"#,
    );

    if case.numerics.parallel_cores > 1 {
        script.push_str(&format!(
            r#"
echo "[Venturi] Decomposing domain for {cores} MPI ranks..."
decomposePar -force | tee log.decomposePar

echo "[Venturi] Running parallel solver ({solver_cmd})..."
mpirun -np {cores} {solver_cmd} -parallel | tee log.solver

echo "[Venturi] Reconstructing fields..."
reconstructPar | tee log.reconstructPar
"#,
            cores = case.numerics.parallel_cores
        ));
    } else {
        script.push_str(&format!(
            r#"
echo "[Venturi] Running solver ({solver_cmd})..."
{solver_cmd} | tee log.solver
"#
        ));
    }

    script.push_str("\ntouch case.foam\necho \"[Venturi] Done. Open case.foam in ParaView.\"\n");
    script
}

fn gen_allclean() -> String {
    r#"#!/bin/sh
cd "${0%/*}" || exit 1
rm -rf constant/polyMesh processor* postProcessing log.* case.foam
for d in [1-9]* 0.[0-9]*; do
    [ -d "$d" ] && rm -rf "$d"
done
echo "[Venturi] Case cleaned."
"#
    .to_string()
}

